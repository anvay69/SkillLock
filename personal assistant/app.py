"""Simple Gemini API Personal Assistant Chatbot.

Runs a standalone lightweight web server with a ChatGPT-style UI,
or an interactive terminal CLI mode.
Uses only Python standard library - no external packages required!
"""

import argparse
import http.server
import json
import os
from pathlib import Path
import sys
from urllib.error import HTTPError, URLError
from urllib.request import Request, urlopen

CURRENT_DIR = Path(__file__).resolve().parent
DEFAULT_MODEL = "gemini-3.8-flash"


def call_gemini(message: str, api_key: str, model: str = DEFAULT_MODEL, history: list = None) -> str:
    """Call Google Gemini generateContent REST API."""
    if not api_key or not api_key.strip():
        return "Error: Gemini API key is required. Please provide your key in the settings or set GEMINI_API_KEY environment variable."

    api_key = api_key.strip()
    model = (model or DEFAULT_MODEL).strip()
    url = f"https://generativelanguage.googleapis.com/v1beta/models/{model}:generateContent?key={api_key}"

    # Build conversation contents
    contents = []
    if history:
        for item in history:
            role = "user" if item.get("role") == "user" else "model"
            contents.append({"role": role, "parts": [{"text": item.get("text", "")}]})
    contents.append({"role": "user", "parts": [{"text": message}]})

    payload = {
        "contents": contents,
        "generationConfig": {
            "temperature": 0.7,
            "maxOutputTokens": 2048,
        },
    }

    req = Request(
        url,
        data=json.dumps(payload).encode("utf-8"),
        headers={"Content-Type": "application/json"},
        method="POST",
    )

    try:
        with urlopen(req, timeout=30) as response:
            body = response.read()
        data = json.loads(body.decode("utf-8"))
        candidates = data.get("candidates", [])
        if not candidates:
            return "No response generated by Gemini."
        parts = candidates[0].get("content", {}).get("parts", [])
        reply = "".join(part.get("text", "") for part in parts)
        return reply.strip() or "Empty response received."
    except HTTPError as err:
        try:
            err_body = json.loads(err.read().decode("utf-8"))
            err_msg = err_body.get("error", {}).get("message", str(err))
        except Exception:
            err_msg = str(err)
        return f"Gemini API Error (HTTP {err.code}): {err_msg}"
    except (URLError, TimeoutError) as err:
        return f"Network Error: Could not connect to Gemini API ({err})."
    except Exception as err:
        return f"Unexpected Error: {err}"


class ChatHandler(http.server.SimpleHTTPRequestHandler):
    """Serve static web files and handle chat API requests."""

    def __init__(self, *args, **kwargs):
        super().__init__(*args, directory=str(CURRENT_DIR), **kwargs)

    def do_POST(self):
        if self.path == "/api/chat":
            content_length = int(self.headers.get("Content-Length", 0))
            post_data = self.rfile.read(content_length)

            try:
                body = json.loads(post_data.decode("utf-8"))
                message = body.get("message", "").strip()
                api_key = body.get("api_key", "").strip() or os.getenv("GEMINI_API_KEY", "")
                model = body.get("model", "").strip() or DEFAULT_MODEL
                history = body.get("history", [])

                if not message:
                    reply = "Please enter a message."
                else:
                    reply = call_gemini(message, api_key=api_key, model=model, history=history)

                response_data = {"reply": reply}
                response_bytes = json.dumps(response_data).encode("utf-8")

                self.send_response(200)
                self.send_header("Content-Type", "application/json; charset=utf-8")
                self.send_header("Content-Length", str(len(response_bytes)))
                self.end_headers()
                self.wfile.write(response_bytes)
            except Exception as e:
                err_bytes = json.dumps({"error": str(e)}).encode("utf-8")
                self.send_response(500)
                self.send_header("Content-Type", "application/json; charset=utf-8")
                self.send_header("Content-Length", str(len(err_bytes)))
                self.end_headers()
                self.wfile.write(err_bytes)
        else:
            self.send_error(404, "Not Found")

    def log_message(self, format, *args):
        # Clean logging
        sys.stdout.write(f"[{self.log_date_time_string()}] {args[0]} {args[1]}\n")


def run_cli():
    print("==================================================")
    print("       Personal Assistant (Gemini CLI Mode)       ")
    print("==================================================")
    api_key = os.getenv("GEMINI_API_KEY", "").strip()
    if not api_key:
        api_key = input("Enter your GEMINI_API_KEY: ").strip()

    history = []
    print("\nChatbot is ready! (Type 'quit' or 'exit' to stop)\n")
    while True:
        try:
            user_msg = input("\nYou: ").strip()
            if not user_msg:
                continue
            if user_msg.lower() in {"exit", "quit"}:
                print("Goodbye!")
                break

            reply = call_gemini(user_msg, api_key=api_key, history=history)
            print(f"\nAssistant: {reply}")

            history.append({"role": "user", "text": user_msg})
            history.append({"role": "model", "text": reply})
        except (KeyboardInterrupt, EOFError):
            print("\nExiting...")
            break


def run_server(port: int = 8080):
    server_address = ("127.0.0.1", port)
    httpd = http.server.HTTPServer(server_address, ChatHandler)
    url = f"http://localhost:{port}"
    print("==================================================")
    print("        Personal Assistant Chatbot Running        ")
    print("==================================================")
    print(f" Web UI: {url}")
    print(" Press Ctrl+C to stop the server.")
    print("==================================================")
    try:
        httpd.serve_forever()
    except KeyboardInterrupt:
        print("\nStopping server...")
        httpd.server_close()


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Personal Assistant Gemini Chatbot")
    parser.add_argument("--cli", action="store_true", help="Run in terminal CLI mode")
    parser.add_argument("--port", type=int, default=8080, help="Port to run web server on (default: 8080)")
    args = parser.parse_args()

    if args.cli:
        run_cli()
    else:
        run_server(args.port)

